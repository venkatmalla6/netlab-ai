import React, { useState, useRef, useEffect } from 'react'
import { useSearchParams } from 'react-router-dom'
import { Terminal as TerminalIcon, Play, RefreshCw, Layers, ShieldCheck, Copy, Check, Sparkles } from 'lucide-react'
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from '@/components/ui/card'
import { Button } from '@/components/ui/button'
import { Badge } from '@/components/ui/badge'
import { apiClient } from '@/services/api'

interface DeviceOption {
  id: number
  name: string
  vendor: string
  platform: string
  management_ip: string
  device_type?: string
}

export const DeviceTerminal: React.FC = () => {
  const [searchParams] = useSearchParams()
  const targetDeviceQuery = searchParams.get('device')

  const [devices, setDevices] = useState<DeviceOption[]>([])
  const [selectedDeviceId, setSelectedDeviceId] = useState<number>(1)
  const [device, setDevice] = useState<string>('Router-1')
  const [history, setHistory] = useState<string[]>([
    'NETLAB AI Device Terminal Console v2.0.0 (Phase 2)',
    'Real-time execution shell connected to local SQLite device engine & automation adapter.',
    'Available quick commands: show ip int brief | show ip route | show run | show version | ping <ip>',
    '',
    'Router-1# ',
  ])
  const [cmdInput, setCmdInput] = useState<string>('')
  const [isExecuting, setIsExecuting] = useState<boolean>(false)
  const [commandHistory, setCommandHistory] = useState<string[]>([])
  const [historyPointer, setHistoryPointer] = useState<number>(-1)
  const terminalEndRef = useRef<HTMLDivElement>(null)

  useEffect(() => {
    apiClient
      .getDevices()
      .then((data: DeviceOption[]) => {
        if (data && data.length > 0) {
          setDevices(data)

          // Check if specific device requested in URL
          const match = targetDeviceQuery
            ? data.find((d) => d.name.toLowerCase() === targetDeviceQuery.toLowerCase() || d.id.toString() === targetDeviceQuery)
            : null

          const active = match || data[0]
          setSelectedDeviceId(active.id)
          setDevice(active.name)
          setHistory([
            `Connected to ${active.name} (${active.vendor.toUpperCase()} ${active.platform || 'native'} - ${active.management_ip || '10.0.0.1'}).`,
            'Type Cisco IOS commands below. Responses are generated by live hardware adapters.',
            `${active.name}# `,
          ])
        }
      })
      .catch(() => {})
  }, [targetDeviceQuery])

  useEffect(() => {
    terminalEndRef.current?.scrollIntoView({ behavior: 'smooth' })
  }, [history])

  const executeCommandString = async (cmdToRun: string) => {
    const cmd = cmdToRun.trim()
    if (!cmd || isExecuting) return

    if (cmd === 'clear') {
      setHistory([`${device}# `])
      setCmdInput('')
      return
    }

    // Add to command history buffer
    setCommandHistory((prev) => [...prev, cmd])
    setHistoryPointer(-1)

    setHistory((prev) => [...prev, `${device}# ${cmd}`])
    setCmdInput('')
    setIsExecuting(true)

    try {
      const resp = await apiClient.executeCommands({
        device_id: selectedDeviceId,
        commands: [cmd],
        mode: 'assisted',
        confirmed: true,
      })

      const outputText = resp.results?.[0]?.output || resp.explanation || 'Command accepted.'
      setHistory((prev) => [...prev, outputText, `${device}# `])
    } catch (err: any) {
      setHistory((prev) => [
        ...prev,
        `% Error executing command: ${err.response?.data?.detail || err.message}`,
        `${device}# `,
      ])
    } finally {
      setIsExecuting(false)
    }
  }

  const handleCommand = (e: React.FormEvent) => {
    e.preventDefault()
    executeCommandString(cmdInput)
  }

  const handleKeyDown = (e: React.KeyboardEvent<HTMLInputElement>) => {
    if (e.key === 'ArrowUp') {
      e.preventDefault()
      if (commandHistory.length === 0) return
      const nextPointer = historyPointer === -1 ? commandHistory.length - 1 : Math.max(0, historyPointer - 1)
      setHistoryPointer(nextPointer)
      setCmdInput(commandHistory[nextPointer])
    } else if (e.key === 'ArrowDown') {
      e.preventDefault()
      if (historyPointer === -1) return
      const nextPointer = historyPointer + 1
      if (nextPointer >= commandHistory.length) {
        setHistoryPointer(-1)
        setCmdInput('')
      } else {
        setHistoryPointer(nextPointer)
        setCmdInput(commandHistory[nextPointer])
      }
    }
  }

  const switchDevice = (newId: number) => {
    setSelectedDeviceId(newId)
    const found = devices.find((d) => d.id === newId)
    if (found) {
      setDevice(found.name)
      setHistory((prev) => [
        ...prev,
        `\n--- Switched session to ${found.name} (${found.vendor.toUpperCase()} ${found.management_ip || ''}) ---`,
        `${found.name}# `,
      ])
    }
  }

  const quickCommands = [
    'show ip int brief',
    'show ip route',
    'show version',
    'show run',
    'show vlan brief',
    'ping 10.0.0.1',
  ]

  return (
    <div className="space-y-6">
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold tracking-tight text-white flex items-center gap-2">
            <TerminalIcon className="h-6 w-6 text-emerald-400" />
            Interactive Device Terminal Console
          </h1>
          <p className="text-sm text-slate-400">
            Real CLI session connected to active devices in netlab.db with live syntax parsing and execution.
          </p>
        </div>

        <div className="flex items-center gap-2">
          {devices.length > 0 ? (
            <select
              value={selectedDeviceId}
              onChange={(e) => switchDevice(parseInt(e.target.value, 10))}
              className="bg-[#090d16] border border-slate-800 rounded-lg px-3 py-1.5 text-xs text-white focus:outline-none focus:border-blue-500 font-mono"
            >
              {devices.map((d) => (
                <option key={d.id} value={d.id}>
                  {d.name} ({d.vendor.toUpperCase()} {d.platform || d.device_type} - {d.management_ip})
                </option>
              ))}
            </select>
          ) : (
            <Badge variant="outline" className="text-xs text-slate-400">
              Target: {device}
            </Badge>
          )}

          <Badge variant="success" className="text-xs font-mono">
            VTY ACTIVE
          </Badge>
        </div>
      </div>

      {/* Quick Macro Commands Bar */}
      <div className="flex items-center gap-2 overflow-x-auto py-1">
        <span className="text-[11px] text-slate-500 font-medium shrink-0 flex items-center gap-1">
          <Sparkles className="h-3 w-3 text-emerald-400" /> Quick Macros:
        </span>
        {quickCommands.map((qc) => (
          <button
            key={qc}
            onClick={() => executeCommandString(qc)}
            disabled={isExecuting}
            className="px-2.5 py-1 rounded bg-slate-900 border border-slate-800 text-[11px] font-mono text-slate-300 hover:text-white hover:border-emerald-500/60 transition-all cursor-pointer whitespace-nowrap shrink-0"
          >
            {qc}
          </button>
        ))}
      </div>

      <Card className="border-slate-800 bg-[#040810] shadow-2xl overflow-hidden">
        <CardHeader className="py-2.5 px-4 bg-[#090e1a] border-b border-slate-800/80 flex flex-row items-center justify-between">
          <div className="flex items-center gap-2">
            <div className="h-3 w-3 rounded-full bg-red-500/80" />
            <div className="h-3 w-3 rounded-full bg-amber-500/80" />
            <div className="h-3 w-3 rounded-full bg-emerald-500/80" />
            <span className="font-mono text-xs text-slate-400 ml-2">
              ssh://admin@{device} [port 22]
            </span>
          </div>

          <Button
            variant="ghost"
            size="sm"
            onClick={() => setHistory([`${device}# `])}
            className="h-6 px-2 text-[10px] text-slate-400 hover:text-white"
          >
            Clear Screen
          </Button>
        </CardHeader>

        <CardContent className="p-4 font-mono text-xs text-emerald-400">
          <div className="max-h-[500px] min-h-[340px] overflow-y-auto space-y-1 select-text">
            {history.map((line, i) => (
              <div key={i} className="whitespace-pre-wrap leading-relaxed">
                {line}
              </div>
            ))}
            <div ref={terminalEndRef} />
          </div>

          <form onSubmit={handleCommand} className="mt-3 flex items-center gap-2 pt-2 border-t border-slate-800/80">
            <span className="text-emerald-500 font-bold select-none">{device}#</span>
            <input
              type="text"
              value={cmdInput}
              onChange={(e) => setCmdInput(e.target.value)}
              onKeyDown={handleKeyDown}
              disabled={isExecuting}
              className="flex-1 bg-transparent border-none text-xs text-emerald-300 focus:outline-none font-mono"
              placeholder={isExecuting ? 'Executing command against device adapter...' : 'Type command (e.g. show ip int brief) and hit Enter...'}
              autoFocus
            />
          </form>
        </CardContent>
      </Card>
    </div>
  )
}
